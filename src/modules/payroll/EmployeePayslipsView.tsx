import React from 'react';
import { useAuth } from '../../contexts/AuthContext';
import { useTenant } from '../../contexts/TenantContext';
import { useHrmsData } from '../../contexts/HrmsDataContext';
import { Payslip } from '../../types';
import {
  FileText,
  Download,
  Eye,
  ShieldCheck
} from 'lucide-react';

